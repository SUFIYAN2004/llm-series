"""Hyena

Implicit long convolutions (filters generated by a small MLP) combined with multiplicative gating; a sub-quadratic attention replacement.

Reference: Poli et al. 2023
"""
import math
import torch
import torch.nn as nn
from ..layers import Block, LM, SwiGLU, fftconv, nocast


class Hyena(nn.Module):  # order-2 Hyena operator, implicit long filters
    def __init__(s, d, order=2, emb=17, hid=64):
        super().__init__(); s.d, s.order = d, order; c = (order + 1) * d
        s.inp = nn.Linear(d, c); s.short = nn.Conv1d(c, c, 3, padding=2, groups=c)
        s.f1 = nn.Linear(emb, hid); s.f2 = nn.Linear(hid, hid); s.f3 = nn.Linear(hid, order * d, bias=False)
        s.freq = nn.Parameter(torch.ones(hid) * 3.0)
        s.register_buffer("decay", torch.exp(torch.linspace(math.log(0.5), math.log(30), order * d)))
        s.bias = nn.Parameter(torch.randn(order, d) * 0.1); s.o = nn.Linear(d, d)
    def filters(s, T, dev):
        t = torch.arange(T, device=dev).float() / T; f = torch.arange(1, 9, device=dev).float()
        feats = torch.cat([t[:, None], torch.sin(2 * math.pi * f * t[:, None]), torch.cos(2 * math.pi * f * t[:, None])], -1)
        h = s.f3(torch.sin(s.freq * s.f2(torch.sin(s.freq * s.f1(feats)))))
        return (h * torch.exp(-t[:, None] * s.decay)).T.reshape(s.order, s.d, T)
    def forward(s, x):
        B, T, D = x.shape
        u = s.short(s.inp(x).transpose(1, 2))[..., :T].split(D, 1)
        with nocast():
            h = s.filters(T, x.device); v = u[0]
            for o in range(s.order): v = u[o + 1].float() * fftconv(v, h[o], s.bias[o])
        return s.o(v.transpose(1, 2))


def build(d):
    H = max(d // 32, 1)
    kvh = H // 2 if H % 2 == 0 else H
    return LM(d, [Block(d, Hyena(d), SwiGLU(d)) for _ in range(8)])
